"""
Install the software environment of the páramo streamflow workflow (run before any stage).

This file is the single source of dependencies. requirements.txt is generated from it.

Usage (from the project folder)
  python install_environment.py --venv              create .venv/ and install everything
  python install_environment.py                     install into the current interpreter
  python install_environment.py --cuda cu124        PyTorch with GPU support (default: CPU)
  python install_environment.py --no-r              skip the R packages
  python install_environment.py --check             only check what is installed
  python install_environment.py --gee-auth          interactive Earth Engine authentication

Outputs
  requirements.txt          generated from PYTHON_PACKAGES (PyTorch is installed separately)
  requirements-lock.txt     pip freeze, exact versions for reproducibility
  outputs/environment_versions.csv

Next step
  python verify.py, then python run_pipeline.py
"""
from __future__ import annotations

import argparse
import csv
import glob
import importlib
import importlib.metadata as md
import os
import platform
import shutil
import subprocess
import sys
import time
import venv
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TESTED = ((3, 11), (3, 12), (3, 13), (3, 14))

# group: (stages, [(pip requirement, import name), ...])
PYTHON_PACKAGES = {
    "base": ("00-14", [("numpy", "numpy"), ("pandas>=2.1", "pandas"), ("pyarrow", "pyarrow"),
                       ("pyyaml", "yaml"), ("scipy", "scipy"), ("matplotlib", "matplotlib")]),
    "geo": ("00, 03, 07", [("pyproj", "pyproj"), ("shapely>=2", "shapely"),
                           ("geopandas", "geopandas"), ("rasterio", "rasterio"),
                           ("pysheds>=0.4", "pysheds")]),
    "gee": ("04", [("earthengine-api", "ee")]),
    "ml": ("06, 10, 11", [("scikit-learn", "sklearn"), ("lightgbm>=4", "lightgbm")]),
}
TORCH = ("torch", "torch")                      # stage 09, installed separately (CPU/CUDA)
R_PACKAGES = ["airGR", "yaml"]                  # stage 08
CRAN = "https://cloud.r-project.org"
PIP_RETRIES, PIP_WAIT_S = 3, 20


def info(msg):
    print(f"[install] {msg}", flush=True)


def run(cmd: list[str]) -> int:
    info("$ " + " ".join(cmd))
    return subprocess.run(cmd).returncode


def pip_install(args: list[str]) -> bool:
    """pip install with retries: on Windows, antivirus scans or an open editor can lock files
    briefly (WinError 32); pip skips what is already installed when retried."""
    cmd = [sys.executable, "-m", "pip", "install", "--upgrade", *args]
    for attempt in range(1, PIP_RETRIES + 1):
        if run(cmd) == 0:
            return True
        if attempt < PIP_RETRIES:
            info(f"pip failed (attempt {attempt}/{PIP_RETRIES}); retrying in {PIP_WAIT_S} s")
            time.sleep(PIP_WAIT_S)
    if os.name == "nt":
        info("If the error is WinError 32 (file in use): close editors and terminals that use "
             ".venv, exclude the project folder from real-time antivirus scanning and pause "
             "cloud synchronisation, then run again.")
    return False


def venv_python() -> Path:
    return ROOT / ".venv" / ("Scripts/python.exe" if os.name == "nt" else "bin/python")


def in_project_venv() -> bool:
    return Path(sys.prefix).resolve() == (ROOT / ".venv").resolve()


def find_rscript() -> str | None:
    found = shutil.which("Rscript")
    if found:
        return found
    if os.name == "nt":
        candidates = sorted(glob.glob(r"C:\Program Files\R\R-*\bin\Rscript.exe"))
        return candidates[-1] if candidates else None
    return None


def write_requirements():
    lines = ["# Generated by install_environment.py. PyTorch is installed separately."]
    for group, (stages, pkgs) in PYTHON_PACKAGES.items():
        lines.append(f"\n# {group} (stages {stages})")
        lines += [p for p, _ in pkgs]
    (ROOT / "requirements.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


def install_python(cuda: str | None, with_torch: bool) -> bool:
    ok = pip_install(["pip", "setuptools", "wheel"])
    if with_torch:
        args = [TORCH[0]]
        if cuda:
            args += ["--index-url", f"https://download.pytorch.org/whl/{cuda}"]
        elif platform.system() == "Linux":          # the PyPI wheel bundles CUDA on Linux
            args += ["--index-url", "https://download.pytorch.org/whl/cpu"]
        ok &= pip_install(args)
    ok &= pip_install([p for _, pkgs in PYTHON_PACKAGES.values() for p, _ in pkgs])
    return ok


def install_r(rscript: str) -> bool:
    vec = "c(" + ",".join(f'"{p}"' for p in R_PACKAGES) + ")"
    code = (f"pk <- {vec}; miss <- pk[!pk %in% rownames(installed.packages())]; "
            f'if (length(miss)) install.packages(miss, repos="{CRAN}")')
    return run([rscript, "-e", code]) == 0


def check(with_torch: bool, rscript: str | None, with_r: bool) -> bool:
    rows, ok = [], True
    pairs = [(g, p, m) for g, (_, pkgs) in PYTHON_PACKAGES.items() for p, m in pkgs]
    if with_torch:
        pairs.append(("dl", *TORCH))
    for group, req, module in pairs:
        dist = req.split(">")[0].split("=")[0]
        try:
            importlib.import_module(module)
            version, status = md.version(dist), "ok"
        except Exception as err:  # noqa: BLE001
            version, status, ok = "", f"ERROR: {type(err).__name__}: {err}"[:100], False
        rows.append({"language": "python", "group": group, "package": dist,
                     "version": version, "status": status})
    if with_r:
        if rscript is None:
            rows.append({"language": "R", "group": "r", "package": "Rscript", "version": "",
                         "status": "ERROR: R not found"})
            ok = False
        else:
            for p in R_PACKAGES:
                r = subprocess.run([rscript, "-e", f'cat(as.character(packageVersion("{p}")))'],
                                   capture_output=True, text=True)
                ok &= r.returncode == 0
                rows.append({"language": "R", "group": "r", "package": p,
                             "version": r.stdout.strip() if r.returncode == 0 else "",
                             "status": "ok" if r.returncode == 0 else "ERROR: not installed"})
    d = ROOT / "outputs"
    d.mkdir(parents=True, exist_ok=True)
    with open(d / "environment_versions.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    width = max(len(r["package"]) for r in rows)
    for r in rows:
        print(f"  {r['language']:<6} {r['group']:<5} {r['package']:<{width}}  "
              f"{r['version']:<12} {r['status']}")
    return ok


def freeze():
    r = subprocess.run([sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True)
    (ROOT / "requirements-lock.txt").write_text(
        f"# pip freeze | Python {platform.python_version()} | {platform.platform()}\n" + r.stdout,
        encoding="utf-8")


def gee_auth():
    import ee
    import yaml
    project = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))["gee"]["project"]
    try:
        ee.Initialize(project=project)
        info(f"Earth Engine already authenticated (project {project})")
    except Exception:  # noqa: BLE001
        ee.Authenticate()
        ee.Initialize(project=project)
        info(f"Earth Engine authenticated (project {project})")


def main():
    ap = argparse.ArgumentParser(description="Install the páramo workflow environment")
    ap.add_argument("--venv", action="store_true")
    ap.add_argument("--cuda", help="PyTorch CUDA variant, e.g. cu121 or cu124")
    ap.add_argument("--no-torch", action="store_true")
    ap.add_argument("--no-r", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--gee-auth", action="store_true")
    a = ap.parse_args()

    info(f"Python {platform.python_version()} ({sys.executable}) on {platform.system()}")
    if sys.version_info[:2] < (3, 10):
        sys.exit("Python >= 3.10 is required")
    if sys.version_info[:2] not in TESTED:
        info("warning: Python version not among the tested ones (3.11-3.14)")
    if a.venv and not in_project_venv():
        if not venv_python().exists():
            info("Creating .venv/")
            venv.create(ROOT / ".venv", with_pip=True)
        args = [x for x in sys.argv[1:] if x != "--venv"]
        sys.exit(subprocess.run([str(venv_python()), str(Path(__file__).resolve()), *args]).returncode)

    with_torch, with_r = not a.no_torch, not a.no_r
    rscript = find_rscript() if with_r else None
    write_requirements()
    if not a.check:
        if not install_python(a.cuda, with_torch):
            info("pip reported errors; see the messages above")
        if with_r:
            if rscript:
                install_r(rscript)
            else:
                info("R not found: install R >= 4.2 (https://cran.r-project.org) or use --no-r")
        freeze()
    if a.gee_auth:
        gee_auth()
    ok = check(with_torch, rscript, with_r)
    info("Environment ready. Next: python verify.py, then python run_pipeline.py" if ok
         else "Some packages failed; see outputs/environment_versions.csv")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
